const lc = (s: string) => (s ? s.charAt(0).toLowerCase() + s.slice(1) : s);
const trimDot = (s: string) => s.trim().replace(/[.!?…]+$/, '');

const choice = (
  kind: MoveKind,
  text: string,
  next: string,
  tone: ToneId,
  explanation?: string,
  delta?: Partial<Metrics>,
): Choice => ({
  kind,
  text,
  next,
  delta: { ...BASE_DELTA[kind], ...delta },
  reaction: REACTION[tone][kind],
  explanation: explanation ?? EXPLAIN[kind],
});

const ending = (id: string, line: string, progress: number, e: Ending, emotion: string): GraphNode => ({
  id,
  stage: 'Финал',
  emotion,
  line,
  progress,
  options: [],
  ending: e,
});

export function buildGraph(cfg: ScenarioConfig): ScenarioGraph {
  const t = cfg.partner.tone;
  const s: ScenarioSlots = cfg.slots;
  const tone = toneById(t);
  const offer = trimDot(s.userOffer);
  const fact = trimDot(s.argumentFact);
  const guarantee = trimDot(s.guarantee);

  const nodes: GraphNode[] = [
    {
      id: 'open',
      stage: 'Позиция',
      emotion: t === 'aggressive' ? 'Раздражение' : t === 'tough' ? 'Давление' : 'Настороженность',
      line: `${tone.opener} Тема — ${lc(trimDot(cfg.topic))}. ${s.objection}`,
      progress: 10,
      options: [
        choice('question', 'Прежде чем отвечать, хочу понять вашу позицию: что для вас в этом вопросе самое важное и почему?', 'reveal', t),
        choice('argued', `${fact}. Поэтому предлагаю обсудить такой вариант: ${lc(offer)}.`, 'counter', t),
        choice('neutral', 'Понимаю. Давайте посмотрим, что можно сделать.', 'push', t),
        choice('aggressive', 'Если вас это не устраивает — это не наша проблема. Условия такие, какие есть.', 'cold', t),
      ],
    },
    {
      id: 'reveal',
      stage: 'Интересы',
      emotion: 'Открытость',
      line: `Если честно, для нас главное — ${lc(trimDot(s.hiddenInterest))}. Но есть ограничение: ${lc(trimDot(s.constraint))}.`,
      progress: 40,
      options: [
        choice('argued', `Тогда предлагаю решение под вашу задачу: ${lc(offer)}. Так мы закрываем главное — ${lc(trimDot(s.hiddenInterest))} — и укладываемся в ограничение.`, 'offer', t,
          'Вы построили предложение вокруг раскрытого интереса собеседника. Это самый короткий путь к взаимовыгодному решению.', { argument: 16, trust: 12 }),
        choice('question', `Правильно понимаю: если решим вопрос «${lc(trimDot(s.hiddenInterest))}», остальное можно обсуждать гибко?`, 'offer', t,
          'Резюмирующий вопрос фиксирует интерес собеседника и проверяет, что вы поняли его верно.'),
        choice('neutral', 'Ясно. Мы учтём это.', 'push', t),
        choice('aggressive', 'Ваши ограничения — это ваши сложности, подстраиваться под них мы не обязаны.', 'cold', t),
      ],
    },
    {
      id: 'counter',
      stage: 'Возражение',
      emotion: 'Сомнение',
      line: `Аргумент понятен. Но ${lc(trimDot(s.constraint))} — и это не обсуждается.`,
      progress: 30,
      options: [
        choice('question', 'Помогите понять: что стоит за этим ограничением и что для вас важнее всего?', 'reveal', t),
        choice('argued', `Тогда давайте искать вариант внутри ограничения: ${lc(offer)}. ${fact}.`, 'terms', t),
        choice('neutral', 'Хорошо, тогда подумаем, как быть.', 'push', t),
        choice('aggressive', 'Не обсуждается у вас — не обсуждается и у нас. Тупик.', 'cold', t),
      ],
    },
    {
      id: 'push',
      stage: 'Давление',
      emotion: 'Давление',
      line: `Тогда давайте прямо: ${lc(trimDot(s.concessionDemand))}. Иначе мы не договоримся.`,
      progress: 35,
      options: [
        choice('argued', `Такую уступку я сделать не могу, но могу предложить равноценное: ${lc(offer)}. Это решает вашу задачу без потерь для обеих сторон.`, 'terms', t,
          'Вы не уступили под давлением, а предложили обмен. Отказ + альтернатива — сильнее, чем просто «нет».'),
        choice('question', 'Чтобы найти решение: какую задачу для вас решает это требование?', 'reveal', t,
          'Вопрос о причине требования открывает интересы, стоящие за позицией, — и часто показывает более дешёвый путь к согласию.'),
        choice('neutral', 'Ну хорошо, если по-другому никак — согласен.', 'end_concession', t,
          'Уступка без встречного условия: собеседник получил своё, а вы — ничего. На следующей встрече давление повторится.', { argument: -2, trust: 3, tension: -6 }),
        choice('aggressive', 'Это абсурдное требование. Даже обсуждать не буду.', 'cold', t),
      ],
    },
    {
      id: 'cold',
      stage: 'Эскалация',
      emotion: 'Закрытость',
      line:
        t === 'friendly'
          ? 'Честно говоря, я не ожидал такого тона. Может, начнём заново?'
          : 'Мне не нравится, как идёт разговор. Если так пойдёт и дальше, я предпочту закончить.',
      progress: 15,
      options: [
        choice('question', 'Прошу прощения за резкость. Давайте начнём сначала: что для вас сейчас важнее всего?', 'reveal', t,
          'Признать ошибку и вернуться к интересам собеседника — лучший способ выйти из эскалации.', { trust: 10 }),
        choice('argued', `Извините, я был резок. По существу: ${lc(fact)}.`, 'push', t),
        choice('neutral', 'Хорошо, давайте возьмём паузу и вернёмся к разговору позже.', 'end_postponed', t,
          'Пауза снимает напряжение, но результат не достигнут, а собеседник запомнит конфликт.', { tension: -10 }),
        choice('aggressive', 'Как хотите. Не мы в этом нуждаемся.', 'end_fail', t),
      ],
    },
    {
      id: 'offer',
      stage: 'Решение',
      emotion: 'Интерес',
      line: 'Это уже похоже на решение. Но что, если не получится? Какие у меня гарантии?',
      progress: 70,
      options: [
        choice('argued', `Предлагаю зафиксировать: ${lc(guarantee)}. Вы контролируете результат, а не верите на слово.`, 'end_winwin', t,
          'Проверяемое обязательство вместо обещания закрывает последний риск собеседника.', { trust: 16 }),
        choice('question', 'Что именно стало бы для вас достаточной гарантией?', 'terms', t),
        choice('neutral', 'Мы всегда выполняем обещания, не переживайте.', 'end_deal', t,
          '«Не переживайте» — обещание без механизма контроля. Сделка состоялась, но доверие держится на честном слове.'),
        choice('aggressive', 'Гарантии? Вам мало того, что мы уже предложили?', 'push', t),
      ],
    },
    {
      id: 'terms',
      stage: 'Условия',
      emotion: 'Взвешивание',
      line: 'Допустим. Тогда давайте зафиксируем условия. Что вы готовы гарантировать?',
      progress: 60,
      options: [
        choice('argued', `${guarantee} — это фиксируем письменно. Взамен прошу подтвердить договорённость до конца недели.`, 'end_deal', t,
          'Чёткий обмен обязательствами и следующий шаг с дедлайном — хорошее завершение.'),
        choice('question', 'Что для вас было бы критичным пунктом в этих условиях?', 'offer', t),
        choice('neutral', 'Давайте обсудим детали позже, в рабочем порядке.', 'end_postponed', t,
          'Вы остановились в шаге от договорённости: без фиксации условий разговор придётся начинать заново.'),
        choice('aggressive', 'Гарантировать мы ничего не будем, это ваш риск.', 'end_fail', t),
      ],
    },
    ending('end_winwin', 'Договорились. Это решение я смогу защитить. Фиксируем и двигаемся дальше.', 100, {
      outcome: 'winwin',
      title: 'Взаимовыгодное соглашение',
      text: `Вы выяснили настоящий интерес собеседника («${lc(trimDot(s.hiddenInterest))}») и построили предложение вокруг него, подкрепив гарантией.`,
    }, 'Готовность'),
    ending('end_deal', 'Хорошо, договорились. Посмотрим, как пойдёт.', 85, {
      outcome: 'deal',
      title: 'Договорённость достигнута',
      text: 'Результат есть, но без понимания глубинных интересов собеседника договорённость держится на аргументах, а не на доверии.',
    }, 'Согласие'),
    ending('end_concession', 'Отлично, так и запишем.', 60, {
      outcome: 'concession',
      title: 'Договорённость ценой уступки',
      text: `Вы согласились на требование «${lc(trimDot(s.concessionDemand))}». Лучше было выяснить, какую задачу оно решает, и предложить равноценную замену.`,
    }, 'Удовлетворение'),
    ending('end_postponed', 'Хорошо, вернёмся к этому позже.', 35, {
      outcome: 'postponed',
      title: 'Решение отложено',
      text: 'Разговор закончился без договорённости. Инициатива ушла к собеседнику, и он может выбрать другой вариант.',
    }, 'Нейтралитет'),
    ending('end_fail', 'На этом, думаю, закончим.', 0, {
      outcome: 'fail',
      title: 'Переговоры сорваны',
      text: 'Эскалация перечеркнула возможность договориться. Давление вызвало ответное давление, и стороны разошлись.',
    }, 'Отстранённость'),
  ];

  return { start: 'open', nodes: Object.fromEntries(nodes.map((n) => [n.id, n])) };
}

export const toScenario = (cfg: ScenarioConfig): Scenario => ({ ...cfg, graph: buildGraph(cfg) });

