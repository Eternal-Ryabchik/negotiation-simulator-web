const fromPreset = (
  id: string,
  sphere: string,
  title: string,
  icon: string,
  difficulty: ScenarioConfig['difficulty'],
  briefing: string[],
): Scenario => {
  const p = SPHERE_PRESETS[sphere];
  const cfg: ScenarioConfig = {
    id,
    title,
    sphere,
    topic: p.topic!,
    icon,
    userRole: p.userRole!,
    userGoal: p.userGoal!,
    difficulty,
    partner: p.partner!,
    slots: p.slots,
    keywords: keywordsFrom(`${p.topic} ${Object.values(p.slots).join(' ')}`),
    briefing,
    builtIn: true,
  };
  return toScenario(cfg);
};

